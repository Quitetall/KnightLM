/// Wrap a captured closure in an `UnsyncCallback` so it can live in the (Copy)
/// context. Local callbacks are `Rc`-backed, which is what signal captures need.
pub fn view_callback<In, Out>(f: impl Fn(In) -> Out + 'static) -> UnsyncCallback<In, Out> {
    UnsyncCallback::new(f)
}

