SCHEMAS = Path(__file__).resolve().parents[2] / "crates" / "contract" / "schemas"
MARK = '<tool_call>{"name":"mark_arrow","arguments":{"from":"g1","to":"f3","color":"blue"}}</tool_call>'
STEP = '<tool_call>{"name":"scratch_step","arguments":{"moves":["g1f3","b8c6"]}}</tool_call>'


class GoldenCases(unittest.TestCase):
    """crates/contract/schemas/provisional_cases.json is generated by Rust (model_turn.rs)."""

    def test_python_tracker_equals_the_rust_tracker_on_every_case(self):
        cases = json.loads((SCHEMAS / "provisional_cases.json").read_text())
        self.assertGreaterEqual(len(cases), 10)
        for case in cases:
            with self.subTest(case["text"]):
                got = coach.parse_provisional(case["text"], case["legal"], case["max_attempts"], case["finished"])
                self.assertEqual(
                    {"committed": got.committed, "fallback": got.fallback, "attempts": got.attempts,
                     "accepted": got.accepted, "rejected": got.rejected, "exhausted": got.exhausted,
                     "feedback": got.feedback, "reply": got.reply},
                    {k: case[k] for k in ("committed", "fallback", "attempts", "accepted", "rejected",
                                          "exhausted", "feedback", "reply")})

    def test_the_cases_cover_the_commit_rule(self):
        cases = json.loads((SCHEMAS / "provisional_cases.json").read_text())
        self.assertTrue(any(c["fallback"] for c in cases) and any(not c["fallback"] for c in cases))
        self.assertTrue(any(c["accepted"] > 1 for c in cases), "a revision")
        self.assertTrue(any(c["exhausted"] for c in cases), "retries exhausted")
        self.assertTrue(any(not c["finished"] for c in cases), "a cut stream")


class ParserTests(unittest.TestCase):
    LEGAL = ["e2e4", "g1f3"]

    def test_last_legal_wins_and_an_illegal_later_line_keeps_the_earlier(self):
        r = coach.parse_provisional("Provisional: e2e4\nProvisional: g1f3\nProvisional: e2e9\nok", self.LEGAL, 5)
        self.assertEqual((r.committed, r.moves, r.rejected, r.fallback), ("g1f3", ["e2e4", "g1f3"], 1, False))
        self.assertEqual(r.reply, "ok")

    def test_none_valid_is_the_fallback_marker_with_no_reply(self):
        r = coach.parse_provisional("Provisional: e2e5\nI think so.", self.LEGAL, 3)
        self.assertEqual((r.committed, r.fallback, r.reply), (None, True, None))

    def test_a_cut_stream_ignores_the_unterminated_line(self):
        self.assertEqual(coach.parse_provisional("Provisional: e2e4\nProvisional: g1f", self.LEGAL, 5, False).committed,
                         "e2e4")

    def test_only_whole_lines_with_one_token_count(self):
        for text in ("Provisional: I think e4", "My Provisional: e2e4", "Provisional:", "Provisional: e2e4 g1f3"):
            self.assertIsNone(coach.parse_provisional(text, self.LEGAL).committed, text)


class ToolCallTests(unittest.TestCase):
    def test_coach_calls_are_forwarded_and_everything_else_is_refused(self):
        sneaky = '<tool_call>{"name":"submit_move","arguments":{"reasoning":"a","move":"e2e4"}}</tool_call>'
        app = '<tool_call>{"name":"analyze","arguments":{}}</tool_call>'
        bad_square = '<tool_call>{"name":"mark_square","arguments":{"square":"e4","color":"pink"}}</tool_call>'
        extra = '<tool_call>{"name":"clear_marks","arguments":{"x":1}}</tool_call>'
        ok, refused = coach.forward_tool_calls("\n".join([MARK, sneaky, app, bad_square, extra, "<tool_call>{nope</tool_call>",
                                                          STEP, "<tool_call>{"]))
        self.assertEqual([c["name"] for c in ok], ["mark_arrow", "scratch_step"])
        self.assertEqual(len(refused), 6)
        self.assertIn("submit_move: not a coach tool", refused)
        self.assertIn("analyze: not a coach tool", refused)

    def test_forwarding_follows_the_shared_schema(self):
        names = set(tool_names("coach"))
        self.assertEqual(names, {"scratch_set", "scratch_step", "show_game_move", "mark_arrow", "mark_square",
                                 "clear_marks"})
        ok, _ = coach.forward_tool_calls('<tool_call>{"name":"show_game_move","arguments":{"ply":0}}</tool_call>')
        self.assertEqual(len(ok), 1)
        _, refused = coach.forward_tool_calls('<tool_call>{"name":"show_game_move","arguments":{"ply":-1}}</tool_call>')
        self.assertEqual(len(refused), 1)

    def test_the_reply_has_no_tool_calls_or_provisional_lines(self):
        text = f"Provisional: e2e4\nLook here.{MARK}\nDone."
        self.assertEqual(coach.strip_provisional_lines(coach.strip_tool_calls(text)), "Look here.\nDone.")


class FakeCoach(FakePredictor):
    def __init__(self, text, **kw):
        super().__init__("")
        self.text, self.prompts = text, []

    def predict_coach(self, prompt):
        self.prompts.append(prompt)
        return CoachGeneration(self.text, 11, 7)

    def predict(self, packet, mode):
        return Prediction("g1f3", " g1f3", True, 4, 2, 1.0)


COACH_TEXT = f"Provisional: e2e4\nProvisional: g1f3\nThe knight comes out before the pawn push.\n{MARK}\n{STEP}"
PACKET_TEXT = json.dumps(PACKET)
BODY = {"model": "knightlm", "knightlm": {"turn": "coach"},
        "messages": [{"role": "user", "content": PACKET_TEXT}]}


class ChatTurnTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def client(self, text=COACH_TEXT, mode="constrained"):
        try:
            from fastapi.testclient import TestClient
        except ImportError:
            self.skipTest("fastapi/httpx not installed")
        import model.serve.server as server

        (Path(self.tmp.name) / "tokenizer.json").write_text("{}")
        (Path(self.tmp.name) / "chat_template.json").write_text("{}")
        self.predictor = FakeCoach(text)
        self.predictor.base_dir = Path(self.tmp.name)
        return TestClient(server.create_app(self.predictor, mode))

    def test_end_to_end_packet_in_move_reply_and_tool_calls_out(self):
        r = self.client().post("/v1/chat/completions", json=BODY)
        self.assertEqual(r.status_code, 200, r.text)
        body = r.json()
        choice = body["choices"][0]
        self.assertEqual(choice["finish_reason"], "tool_calls")
        self.assertEqual(choice["message"]["content"], "The knight comes out before the pawn push.")
        self.assertEqual([c["function"]["name"] for c in choice["message"]["tool_calls"]],
                         ["mark_arrow", "scratch_step"])
        ext = body["knightlm"]
        self.assertEqual((ext["path"], ext["code"], ext["legal"]), ("model", "ok", True))
        self.assertEqual(ext["coach"], {"move": "g1f3", "provisional": ["e2e4", "g1f3"], "rejected": 0,
                                        "fallback": False, "refused_calls": []})
        self.assertEqual(body["usage"], {"prompt_tokens": 11, "completion_tokens": 7, "total_tokens": 18})
        # The move is not a tool call: coach has no submit_move.
        self.assertNotIn("submit_move", [c["function"]["name"] for c in choice["message"]["tool_calls"]])

    def test_response_matches_the_published_coach_example(self):
        example = json.loads((SCHEMAS / "chat_completion_coach_example.json").read_text())
        body = self.client().post("/v1/chat/completions", json=BODY).json()
        self.assertEqual(body["choices"][0]["message"]["content"], example["choices"][0]["message"]["content"])
        for got, want in zip(body["choices"][0]["message"]["tool_calls"], example["choices"][0]["message"]["tool_calls"]):
            self.assertEqual((got["function"]["name"], got["function"]["arguments"]),
                             (want["function"]["name"], want["function"]["arguments"]))
        self.assertEqual(body["knightlm"]["coach"], example["knightlm"]["coach"])
        self.assertEqual(set(body["knightlm"]), set(example["knightlm"]))

    def test_prompt_is_summary_recent_and_the_fresh_packet_with_both_schemas(self):
        client = self.client()
        earlier = [{"role": "user" if i % 2 == 0 else "assistant", "content": f"line {i}"} for i in range(10)]
        body = dict(BODY, knightlm={"turn": "coach", "summary": "U: opening talk"},
                    messages=earlier + [{"role": "system", "content": "ignored"},
                                        {"role": "user", "content": "What now?\n" + play_text(PACKET)}])
        self.assertEqual(client.post("/v1/chat/completions", json=body).status_code, 200)
        prompt = self.predictor.prompts[0]
        shown = {k: v for k, v in PACKET.items() if k != "legal_moves"}
        history = [{"role": m["role"], "text": m["content"]} for m in earlier] + [{"role": "user", "text": "What now?"}]
        from model.prompt import roll_chat
        summary, recent = roll_chat("U: opening talk", history)
        self.assertEqual(prompt, combined_text(shown, "coach", summary, recent))
        self.assertIn("Play tools:", prompt)
        self.assertIn("Coach tools:", prompt)
        self.assertIn("Mode: coach\n", prompt)
        self.assertIn("Conversation summary: ", prompt)
        self.assertNotIn('"legal_moves":', prompt)
        self.assertTrue(prompt.endswith(json.dumps(shown, sort_keys=True, separators=(",", ":"))))
        self.assertEqual(prompt.count("user: ") + prompt.count("assistant: "), 6)

    def test_no_legal_provisional_is_a_labelled_constrained_fallback_without_reply_or_marks(self):
        body = self.client("Provisional: e2e9\nLooks fine.\n" + MARK).post("/v1/chat/completions", json=BODY).json()
        message = body["choices"][0]["message"]
        self.assertEqual((message["content"], "tool_calls" in message, body["choices"][0]["finish_reason"]),
                         (None, False, "stop"))
        self.assertEqual((body["knightlm"]["path"], body["knightlm"]["raw_code"]), ("constrained_move", "no_provisional"))
        self.assertEqual((body["knightlm"]["coach"]["move"], body["knightlm"]["coach"]["fallback"]), ("g1f3", True))

    def test_raw_mode_returns_no_move_instead_of_a_fallback(self):
        body = self.client("nothing usable", mode="raw").post("/v1/chat/completions", json=BODY).json()
        self.assertEqual((body["knightlm"]["legal"], body["knightlm"]["coach"]["move"]), (False, None))

    def test_play_stays_the_default_and_rejects_coach_tools(self):
        client = self.client()
        play_body = {"model": "knightlm", "messages": [{"role": "user", "content": play_text(PACKET)}]}
        for name in ("mark_arrow", "scratch_set", "analyze"):
            tool = {"type": "function", "function": {"name": name}}
            r = client.post("/v1/chat/completions", json=dict(play_body, tools=[tool]))
            self.assertEqual((r.status_code, r.json()["error"]["code"]), (400, "tool_not_allowed"), name)
        r = client.post("/v1/chat/completions", json=dict(play_body, knightlm={"turn": "play"},
                                                           tools=[{"type": "function", "function": {"name": "mark_arrow"}}]))
        self.assertEqual(r.status_code, 400)

    def test_a_coach_turn_shows_both_schemas_but_never_app_tools(self):
        client = self.client()
        for name in tool_names("play") + tool_names("coach"):
            tool = {"type": "function", "function": {"name": name}}
            self.assertEqual(client.post("/v1/chat/completions", json=dict(BODY, tools=[tool])).status_code, 200, name)
        for name in ("analyze", "evaluate", "play_move"):
            tool = {"type": "function", "function": {"name": name}}
            r = client.post("/v1/chat/completions", json=dict(BODY, tools=[tool]))
            self.assertEqual((r.status_code, r.json()["error"]["code"]), (400, "tool_not_allowed"), name)

    def test_bounds_and_bad_turn_are_errors_not_truncation(self):
        client = self.client()
        long = dict(BODY, messages=[{"role": "user", "content": "x" * 801}, BODY["messages"][0]])
        r = client.post("/v1/chat/completions", json=long)
        self.assertEqual((r.status_code, r.json()["error"]["code"]), (422, "chat_too_long"))
        r = client.post("/v1/chat/completions", json=dict(BODY, knightlm={"turn": "coach", "summary": "s" * 1201}))
        self.assertEqual((r.status_code, r.json()["error"]["code"]), (422, "chat_too_long"))
        r = client.post("/v1/chat/completions", json=dict(BODY, knightlm={"turn": "referee"}))
        self.assertEqual((r.status_code, r.json()["error"]["code"]), (422, "bad_turn"))
        self.assertEqual(self.predictor.prompts, [])

    def test_stream_carries_the_reply_then_every_tool_call(self):
        r = self.client().post("/v1/chat/completions", json=dict(BODY, stream=True))
        lines = [l for l in r.text.split("\n\n") if l]
        self.assertEqual(lines[-1], "data: [DONE]")
        chunks = [json.loads(l[len("data: "):]) for l in lines[:-1]]
        deltas = [c["choices"][0]["delta"] for c in chunks if c["choices"]]
        self.assertEqual("".join(d.get("content") or "" for d in deltas),
                         "The knight comes out before the pawn push.")
        heads = [d["tool_calls"][0] for d in deltas if "tool_calls" in d and "id" in d["tool_calls"][0]]
        self.assertEqual([h["function"]["name"] for h in heads], ["mark_arrow", "scratch_step"])
        args = {}
        for d in deltas:
            for t in d.get("tool_calls", []):
                args[t["index"]] = args.get(t["index"], "") + t["function"]["arguments"]
        self.assertEqual(json.loads(args[0])["to"], "f3")
        self.assertEqual(json.loads(args[1])["moves"], ["g1f3", "b8c6"])
        self.assertEqual(chunks[-1]["choices"][0]["finish_reason"], "tool_calls")
        self.assertEqual(chunks[-1]["knightlm"]["coach"]["move"], "g1f3")


class ChatHistoryTests(unittest.TestCase):
    def test_rolls_old_messages_into_the_summary(self):
        earlier = [("user" if i % 2 == 0 else "assistant", f"m{i}") for i in range(10)]
        summary, recent = coach.chat_history(earlier, "", None)
        self.assertEqual(len(recent), 6)
        self.assertTrue(summary.startswith("U: m0 | A: m1"))

    def test_overflow_is_an_error(self):
        with self.assertRaises(coach.ChatError):
            coach.chat_history([("user", "x" * 801)], "")
        with self.assertRaises(coach.ChatError):
            coach.chat_history([], "", "s" * 1201)


