"""Mode prompts and shared tool schemas: byte pins, visibility, Rust/Python parity."""

import hashlib
import json
import unittest

from model import prompt
from model.prompt import INSTRUCTION, coach_text, load_tool_schemas, play_text, tool_names, user_chat, user_text

PACKET = {
    "schema_version": 1,
    "fen": "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1",
    "facts": {"repetition_count": 1, "fifty_move_claim_now": False},
}
# Frozen from the pre-modes prompt: existing corpora and evals depend on these bytes.
LEGACY_TEXT = (
    'Choose a legal chess move. Reply with just the UCI move.\n'
    '{"facts":{"fifty_move_claim_now":false,"repetition_count":1},'
    '"fen":"rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1","schema_version":1}'
)


class LegacyPromptPinned(unittest.TestCase):
    def test_user_text_is_byte_identical(self):
        self.assertEqual(user_text(PACKET), LEGACY_TEXT)
        self.assertEqual(INSTRUCTION, "Choose a legal chess move. Reply with just the UCI move.\n")

    def test_user_chat_shape(self):
        self.assertEqual(user_chat(PACKET), [{"role": "user", "content": [{"type": "text", "text": LEGACY_TEXT}]}])

    def test_legacy_prompt_never_mentions_tools(self):
        self.assertNotIn("tool", user_text(PACKET).lower().split("{")[0])


class ModeVisibility(unittest.TestCase):
    def setUp(self):
        self.schemas = load_tool_schemas()
        self.play = tool_names("play", self.schemas)
        self.coach = tool_names("coach", self.schemas)

    def test_play_prompt_never_contains_coach_tool_names(self):
        text = play_text(PACKET)
        for name in self.coach:
            self.assertNotIn(name, text)
        for name in self.play:
            self.assertIn(name, text)

    def test_coach_prompt_never_contains_play_tool_names(self):
        text = coach_text(PACKET, summary="We discussed the Ruy Lopez.")
        for name in self.play:
            self.assertNotIn(name, text)
        for name in self.coach:
            self.assertIn(name, text)

    def test_tool_sets_are_disjoint_and_engine_free(self):
        self.assertFalse(set(self.play) & set(self.coach))
        for name in self.play + self.coach:
            for banned in ("engine", "analy", "evaluat", "stockfish", "tablebase"):
                self.assertNotIn(banned, name)

    def test_packet_is_last_and_prefix_is_stable(self):
        other = dict(PACKET, fen="8/8/8/8/8/8/8/K6k w - - 0 1")
        a, b = play_text(PACKET), play_text(other)
        pre = prompt.prefix("play")
        self.assertTrue(a.startswith(pre) and b.startswith(pre))
        self.assertTrue(a.endswith(prompt.packet_json(PACKET)))
        c = coach_text(PACKET, summary="s", recent=[{"role": "user", "text": "hi"}])
        self.assertTrue(c.startswith(prompt.prefix("coach")))
        self.assertTrue(c.endswith(prompt.packet_json(PACKET)))
        self.assertEqual(c.count("Position packet:"), 1)

    def test_play_prompt_has_no_chat(self):
        self.assertNotIn("summary", play_text(PACKET).lower())

    def test_unknown_mode_refused(self):
        with self.assertRaises(ValueError):
            prompt.prefix("both")


class ChatContextBounds(unittest.TestCase):
    def test_only_last_messages_kept(self):
        recent = [{"role": "user", "text": f"m{i}"} for i in range(10)]
        ctx = prompt.chat_context(None, recent)
        self.assertNotIn("m3", ctx)
        self.assertIn("m9", ctx)
        self.assertEqual(ctx.count("\n"), prompt.MAX_RECENT_MESSAGES)

    def test_overflow_is_an_error(self):
        with self.assertRaises(ValueError):
            prompt.chat_context("x" * (prompt.MAX_SUMMARY_CHARS + 1))
        with self.assertRaises(ValueError):
            prompt.chat_context(None, [{"role": "user", "text": "x" * (prompt.MAX_MESSAGE_CHARS + 1)}])
        with self.assertRaises(ValueError):
            prompt.chat_context(None, [{"role": "system", "text": "x"}])


class RustParity(unittest.TestCase):
    """The JSON is generated by Rust (tools.rs tests pin it); Python must read it whole."""

    def test_schema_file_shape(self):
        schemas = load_tool_schemas()
        self.assertEqual(schemas["schema_version"], "1.0.0")
        self.assertEqual(sorted(schemas["modes"]), ["coach", "play"])
        for mode, tools in schemas["modes"].items():
            for tool in tools:
                self.assertEqual(sorted(tool), ["description", "name", "parameters"])
                params = tool["parameters"]
                self.assertEqual(params["type"], "object")
                self.assertIs(params["additionalProperties"], False)
                self.assertTrue(set(params["required"]) <= set(params["properties"]))

    def test_prefix_embeds_exact_schema_json(self):
        schemas = load_tool_schemas()
        for mode in prompt.MODES:
            blob = json.dumps(schemas["modes"][mode], sort_keys=True, separators=(",", ":"))
            self.assertIn(blob, prompt.prefix(mode, schemas))

    def test_submit_move_is_play_only_with_reasoning_before_move(self):
        schemas = load_tool_schemas()
        submit = [t for t in schemas["modes"]["play"] if t["name"] == "submit_move"][0]
        self.assertEqual(submit["parameters"]["required"], ["move"])
        self.assertIn("reasoning", submit["parameters"]["properties"])
        self.assertNotIn("submit_move", tool_names("coach", schemas))


